//! Keep captured bubblewrap policy out of process arguments at the spawn boundary.
//! Plans retain their full policy for access checks, hashing and mount translation.
use anyhow::{Context, Result};
use std::{fs::File, process::Command};

/// Build a literal command, moving a RODE bubblewrap prefix into an anonymous
/// argument file on Linux. Target arguments remain available for later appending.
pub fn from_argv(argv: &[String]) -> Result<Command> {
    let program = argv.first().context("Missing executable")?;
    let mut command = Command::new(program);
    #[cfg(target_os = "linux")]
    if let Some((start, end)) = policy(&argv.iter().map(AsRef::as_ref).collect::<Vec<_>>()) {
        use std::os::{fd::AsRawFd, unix::process::CommandExt};
        let file = argument_file(argv[start..end].iter().map(AsRef::as_ref))?;
        let fd = file.as_raw_fd();
        let path = std::ffi::CString::new(format!("/proc/self/fd/{fd}"))?;
        command
            .args(&argv[1..start])
            .args(["--args", &fd.to_string()])
            .args(&argv[end..]);
        // Reopen in each child for an independent offset, including retries and
        // concurrent children of the same Command. Never clear CLOEXEC in the
        // multithreaded parent. The captured file owns the descriptor until spawn.
        unsafe {
            command.pre_exec(move || {
                let fd = file.as_raw_fd();
                let reader = libc::open(path.as_ptr(), libc::O_RDONLY | libc::O_CLOEXEC);
                if reader < 0 {
                    return Err(std::io::Error::last_os_error());
                }
                let result = libc::dup2(reader, fd);
                let error = std::io::Error::last_os_error();
                libc::close(reader);
                if result < 0 {
                    return Err(error);
                }
                Ok(())
            });
        }
        return Ok(command);
    }
    command.args(&argv[1..]);
    Ok(command)
}

/// Compact a PTY's bubblewrap policy without taking over terminal stdin. Retain
/// the returned anonymous file until the child exits: portable-pty closes extra
/// descriptors, so a short shell opens the parent's file before execing bwrap.
pub fn compact_pty(command: &mut portable_pty::CommandBuilder) -> Result<Option<File>> {
    #[cfg(target_os = "linux")]
    {
        use std::{ffi::OsString, os::fd::AsRawFd};
        let argv = command.get_argv();
        if let Some((start, end)) = policy(&argv.iter().map(AsRef::as_ref).collect::<Vec<_>>()) {
            let file = argument_file(argv[start..end].iter().map(AsRef::as_ref))?;
            let mut packed: Vec<OsString> = vec![
                "/bin/sh".into(),
                "-c".into(),
                "exec 3<\"$1\" || exit; shift; exec \"$@\"".into(),
                "rode-sandbox".into(),
                format!("/proc/{}/fd/{}", std::process::id(), file.as_raw_fd()).into(),
            ];
            packed.extend_from_slice(&argv[..start]);
            packed.extend(["--args".into(), "3".into()]);
            packed.extend_from_slice(&argv[end..]);
            *command.get_argv_mut() = packed;
            return Ok(Some(file));
        }
    }
    #[cfg(not(target_os = "linux"))]
    let _ = command;
    Ok(None)
}

#[cfg(target_os = "linux")]
fn policy(argv: &[&std::ffi::OsStr]) -> Option<(usize, usize)> {
    let start = if argv.get(1)? == &"--bwrap-launch" {
        2
    } else {
        1
    };
    if argv.get(start)? != &"--unshare-all" || argv.get(start + 1)? != &"--die-with-parent" {
        return None;
    }
    let mut end = start;
    loop {
        // Option values can themselves be "--". Only consume the vocabulary
        // generated by RODE; unfamiliar prefixes retain their literal argv.
        end += match argv.get(end)?.to_str()? {
            "--" => return Some((start, end)),
            "--unshare-all" | "--die-with-parent" | "--share-net" | "--version" => 1,
            "--bind" | "--ro-bind" | "--setenv" => 3,
            "--proc" | "--dev" | "--tmpfs" | "--dir" | "--chdir" => 2,
            _ => return None,
        };
    }
}

#[cfg(target_os = "linux")]
fn argument_file<'a>(args: impl Iterator<Item = &'a std::ffi::OsStr>) -> Result<File> {
    use std::{
        io::{Seek, Write},
        os::{
            fd::{AsRawFd, FromRawFd},
            unix::ffi::OsStrExt,
        },
    };
    let mut file = tempfile::tempfile()?;
    // Keep the descriptor clear of stdio even when invoked with closed streams.
    if file.as_raw_fd() < 3 {
        let fd = unsafe { libc::fcntl(file.as_raw_fd(), libc::F_DUPFD_CLOEXEC, 3) };
        anyhow::ensure!(fd >= 0, "Cannot allocate sandbox argument descriptor");
        file = unsafe { File::from_raw_fd(fd) };
    }
    for arg in args {
        anyhow::ensure!(!arg.as_bytes().contains(&0), "NUL in sandbox argument");
        file.write_all(arg.as_bytes())?;
        file.write_all(&[0])?;
    }
    file.rewind()?;
    Ok(file)
}

#[cfg(all(test, target_os = "linux"))]
mod tests {
    use super::*;
    use std::{
        io::{Read, Write},
        process::Stdio,
        time::Duration,
    };

    fn fixture(bundled: bool) -> Vec<String> {
        // Parallel forks can retain a freshly written executable's writer until
        // exec, causing ETXTBSY even after the creating thread closes it.
        let binary =
            std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/bwrap.sh");
        let mut argv = vec![binary.to_str().unwrap().into()];
        if bundled {
            argv.push("--bwrap-launch".into());
        }
        argv.extend(
            [
                "--unshare-all",
                "--die-with-parent",
                "--ro-bind",
                "/private 'quoted' $path 🦀\nwith newline",
                "/destination",
                "--setenv",
                "POLICY",
                "--",
                "--",
                "/bin/cat",
            ]
            .into_iter()
            .map(str::to_owned),
        );
        argv
    }

    #[test]
    fn compact_commands_keep_literal_policy_stdin_and_independent_spawn_offsets() {
        for bundled in [false, true] {
            let root = tempfile::tempdir().unwrap();
            let argv = fixture(bundled);
            let log = root.path().join("arguments");
            let mut command = from_argv(&argv).unwrap();
            command
                .env("ARGUMENT_LOG", &log)
                .stdin(Stdio::piped())
                .stdout(Stdio::piped());
            let mut children = Vec::new();
            for _ in 0..4 {
                let mut child = command.spawn().unwrap();
                child
                    .stdin
                    .take()
                    .unwrap()
                    .write_all(b"binary stdin\0\xff\n")
                    .unwrap();
                children.push(child);
            }
            let start = if bundled { 2 } else { 1 };
            let mut expected = argv[start..].join("\0").into_bytes();
            expected.extend_from_slice(b"\0binary stdin\0\xff\n");
            for child in children {
                let output = child.wait_with_output().unwrap();
                assert!(output.status.success());
                assert_eq!(output.stdout, expected);
            }
            let visible = std::fs::read_to_string(log).unwrap();
            assert!(visible.contains("--args\0"));
            assert!(!visible.contains("/private"), "{visible}");
        }
    }

    #[test]
    fn compact_pty_reopens_policy_after_descriptor_cleanup_and_keeps_input() {
        let root = tempfile::tempdir().unwrap();
        let argv = fixture(true);
        let log = root.path().join("arguments");
        let mut command = portable_pty::CommandBuilder::new(&argv[0]);
        command.args(&argv[1..]);
        command.env("ARGUMENT_LOG", &log);
        let arguments = compact_pty(&mut command).unwrap().unwrap();
        let pair = portable_pty::native_pty_system()
            .openpty(portable_pty::PtySize::default())
            .unwrap();
        // Echo can interleave input with the child's NUL-delimited policy, or
        // satisfy the reader before the child consumes stdin. Disable only
        // terminal echo before spawning; retain ordinary canonical PTY input.
        let fd = pair.master.as_raw_fd().unwrap();
        let mut settings = std::mem::MaybeUninit::<libc::termios>::uninit();
        assert_eq!(unsafe { libc::tcgetattr(fd, settings.as_mut_ptr()) }, 0);
        let mut settings = unsafe { settings.assume_init() };
        settings.c_lflag &= !(libc::ECHO | libc::ECHONL);
        assert_eq!(unsafe { libc::tcsetattr(fd, libc::TCSANOW, &settings) }, 0);
        let mut child = pair.slave.spawn_command(command).unwrap();
        drop(pair.slave);
        let mut reader = pair.master.try_clone_reader().unwrap();
        let mut writer = pair.master.take_writer().unwrap();
        let (tx, rx) = std::sync::mpsc::channel();
        std::thread::spawn(move || {
            let mut bytes = Vec::new();
            let mut buffer = [0; 4096];
            while let Ok(count) = reader.read(&mut buffer) {
                if count == 0 {
                    break;
                }
                bytes.extend_from_slice(&buffer[..count]);
                if bytes.ends_with(b"pty input\r\n") && bytes.contains(&0) {
                    break;
                }
            }
            let _ = tx.send(bytes);
        });
        writer.write_all(b"pty input\n").unwrap();
        let result = rx.recv_timeout(Duration::from_secs(5));
        child.kill().unwrap();
        child.wait().unwrap();
        drop(arguments);
        let output = String::from_utf8(result.unwrap())
            .unwrap()
            .replace("\r\n", "\n");
        assert_eq!(output, format!("{}\0pty input\n", argv[2..].join("\0")));
        let visible = std::fs::read_to_string(log).unwrap();
        assert!(visible.contains("--args\0"));
        assert!(!visible.contains("/private"), "{visible}");
    }
}
